func stackEngineeringRequest(req agent.Request, attrs map[string]string) bool {
	if req.Mode != string(agent.ModeImplement) || req.Workflow == agent.WorkflowBug || attrs[graphexec.AccessAttribute] != "write" {
		return false
	}
	role := attrs["lf_agent_markdown"]
	if req.Delivery != nil && req.Delivery.MainRole != "" {
		role = req.Delivery.MainRole
	}
	return slices.Contains([]string{"story-worker", "implementation-engineer", "unit-test-engineer", "integration-test-engineer", "go-implementation-engineer", "go-unit-test-engineer", "go-integration-test-engineer"}, role)
}

// stackEngineeringGuidance keeps recipes in the existing engineering evidence
// contract. The factory does not launch an additional aggregate check scheduler.
func stackEngineeringGuidance(req agent.Request) (string, error) {
	if req.StackProfile == nil {
		return "", nil
	}
	if err := req.StackProfile.ValidateRetained(); err != nil {
		return "", errors.New("stack-profile: retained configuration is invalid")
	}
	selected := struct {
		Checks      []config.StackCommand     `json:"checks"`
		Setup       []config.StackCommand     `json:"setup"`
		Environment []config.StackEnvironment `json:"environment"`
	}{req.StackProfile.Effective.Checks, req.StackProfile.Effective.Setup, req.StackProfile.Effective.Environment}
	raw, err := json.Marshal(selected)
	if err != nil {
		return "", err
	}
	return "\nAdmitted stack recipes and environment (effective digest " + req.StackProfile.EffectiveDigest + "): " + string(raw) + "\nUse these stack defaults within the assigned story's check scope and existing engineering evidence contract. Record commands actually executed and their outcomes. Existing pinned Bug/Spike recipes and read-only Validate authority remain unchanged.\n", nil
}

func runStackSetup(ctx context.Context, opts Options, req agent.Request, attrs map[string]string) ([]bugchecks.CommandResult, error) {
	if !stackEngineeringRequest(req, attrs) || req.StackProfile == nil || len(req.StackProfile.Effective.Setup) == 0 {
		return nil, nil
	}
	if opts.MCP == nil {
		return nil, errors.New("stack-profile.setup: operator isolation unavailable")
	}
	if err := req.Validate(); err != nil {
		return nil, err
	}
	if err := agent.VerifyRequestDelivery(ctx, req); err != nil {
		return nil, err
	}
	evidencePath, err := naming.RunLogPath(opts.Paths.Home(), req.Ref, req.RunOrdinal)
	if err != nil {
		return nil, err
	}
	evidencePath += ".stack-setup.json"
	if err := os.MkdirAll(filepath.Dir(evidencePath), 0700); err != nil {
		return nil, err
	}
	observations := []bugchecks.CommandResult{}
	retain := func(result bugchecks.CommandResult) error {
		found := false
		for i, previous := range observations {
			if previous.Started.Equal(result.Started) && previous.ExecutableDigest == result.ExecutableDigest {
				observations[i] = result
				found = true
				break
			}
		}
		if !found {
			observations = append(observations, result)
		}
		raw, err := json.Marshal(observations)
		if err != nil {
			return err
		}
		// #nosec G304 -- evidencePath is generated by naming.RunLogPath beneath the factory run-artifact root.
		file, err := os.OpenFile(evidencePath, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0600)
		if err != nil {
			return err
		}
		_, writeErr := file.Write(raw)
		var syncErr error
		if writeErr == nil {
			syncErr = file.Sync()
		}
		return errors.Join(writeErr, syncErr, file.Close())
	}
	return opts.MCP.BugChecksIsolation.RunStackCommands(ctx, req.WorktreePath, req.StackProfile, "setup", retain)
}

func validateStackCommandInputs(opts Options, req agent.Request) error {
	if req.StackProfile == nil {
		return nil
	}
	if len(req.StackProfile.Effective.Setup) == 0 && len(req.StackProfile.Effective.Checks) == 0 {
		return nil
	}
	if opts.MCP == nil {
		if len(req.StackProfile.Effective.Setup) > 0 {
			return errors.New("stack-profile.setup: operator isolation unavailable")
		}
		return observeGuidanceCheckInputs(req)
	}
	return opts.MCP.BugChecksIsolation.ObserveStackCommands(req.WorktreePath, req.StackProfile)
}

// Without a factory command executor, check recipes remain guidance consumed
// under the provider's existing permissions. Admission only observes their inputs.
func observeGuidanceCheckInputs(req agent.Request) error {
	if err := req.StackProfile.ValidateRetained(); err != nil {
		return errors.New("stack-profile: retained configuration is invalid")
	}
	root, err := filepath.EvalSymlinks(req.WorktreePath)
	if err != nil {
		return errors.New("stack-profile.checks: worktree unavailable")
	}
	confined := func(name string) (string, error) {
		resolved, err := filepath.EvalSymlinks(filepath.Join(root, name))
		if err != nil {
			return "", err
		}
		rel, err := filepath.Rel(root, resolved)
		if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			return "", errors.New("path escapes worktree")
		}
		return resolved, nil
	}
	for i, c := range req.StackProfile.Effective.Checks {
		cwd, err := confined(c.CWD)
		if err != nil {
			return fmt.Errorf("stack-profile.checks[%d].cwd: outside admitted paths or unavailable", i)
		}
		st, err := os.Stat(cwd)
		if err != nil || !st.IsDir() {
			return fmt.Errorf("stack-profile.checks[%d].cwd: unavailable directory", i)
		}
		name := c.Argv[0]
		if strings.ContainsAny(name, "/\\") {
			if filepath.IsAbs(name) {
				return fmt.Errorf("stack-profile.checks[%d].argv: absolute executable requires operator isolation", i)
			}
			executable, err := confined(filepath.Join(c.CWD, name))
			if err != nil {
				return fmt.Errorf("stack-profile.checks[%d].argv: outside admitted paths or unavailable", i)
			}
			st, err := os.Stat(executable)
			if err != nil || !st.Mode().IsRegular() || st.Mode()&0111 == 0 {
				return fmt.Errorf("stack-profile.checks[%d].argv: executable unavailable", i)
			}
		} else if _, err := config.ResolveExecutable("stack.checks", name, os.Getenv("PATH")); err != nil {
			return fmt.Errorf("stack-profile.checks[%d].argv: required host executable unavailable", i)
		}
	}
	return nil
}
