// Package presentation defines the redacted reply boundary shared by chat
// transports: outcome statuses, conversation rendering and raw attachments. It
// has no command, history, provider or store authority.
package presentation

// MaxRawBytes bounds one raw attachment delivered with a reply.
const MaxRawBytes = 64 << 10

// Status is supplied by the outcome producer, never inferred from raw prose.
type Status string

// Command outcome statuses preserve the producer's assessment.
const (
	Success         Status = "success"
	Refusal         Status = "refusal"
	ReportableError Status = "error"
	Uncertain       Status = "uncertain"
)

// Attachment is part of the same reply operation, not a separate delivery.
type Attachment struct {
	Name    string `json:"name"`
	Content string `json:"content"`
}

// Payload is fixed before transport I/O. Raw details use the factory-owned
// filename; unavailable attachment support needs a separately persisted raw
// inline fallback before another delivery attempt.
type Payload struct {
	Content    string      `json:"content"`
	Attachment *Attachment `json:"attachment,omitempty"`
}

// RawFilename is owned by the factory, not generated by a model.
const RawFilename = "raw-details.txt"
