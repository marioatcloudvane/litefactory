// ErrLogAnalysisConflict identifies a stale writer or reused identity with different input.
var ErrLogAnalysisConflict = errors.New("log analysis: identity conflict or fenced writer")

// ErrLogAnalysisBudget identifies a permanently exhausted analysis allowance.
var ErrLogAnalysisBudget = errors.New("log analysis: work allowance exhausted")

// LogAnalysis retains a standalone invocation, never a synthetic workflow run.
type LogAnalysis struct {
	ID            string          `json:"id"`
	StartKey      string          `json:"start_key,omitempty"`
	RequestDigest string          `json:"request_digest"`
	Scope         json.RawMessage `json:"scope"`
	Limits        json.RawMessage `json:"limits"`
	GrantDigest   string          `json:"grant_digest"`
	Provenance    json.RawMessage `json:"provenance"`
	Generation    int64           `json:"generation"`
	State         string          `json:"state"`
	Disposition   string          `json:"disposition"`
	Calls         int             `json:"calls"`
	OutboundBytes int             `json:"outbound_bytes"`
	CreatedAt     time.Time       `json:"created_at"`
	UpdatedAt     time.Time       `json:"updated_at"`
	Reason        string          `json:"reason,omitempty"`
}

// LogAnalysisEvidence is metadata only; source log bodies are never stored here.
type LogAnalysisEvidence struct {
	ID         int64           `json:"id"`
	AnalysisID string          `json:"analysis_id"`
	Generation int64           `json:"generation"`
	CallKey    string          `json:"call_key"`
	Metadata   json.RawMessage `json:"metadata"`
	CreatedAt  time.Time       `json:"created_at"`
}

// LogAnalysisCandidate carries an upstream-validated unapproved proposal.
type LogAnalysisCandidate struct {
	Key      string                   `json:"key"`
	Proposal StandardsProposalVersion `json:"proposal"`
}

// LogAnalysisProposalLink freezes the exact version generated by an analysis.
type LogAnalysisProposalLink struct {
	CandidateKey string `json:"candidate_key"`
	ProposalID   string `json:"proposal_id"`
	Version      int64  `json:"version"`
	BaseRevision int64  `json:"base_revision"`
	ChangeDigest string `json:"change_digest"`
	ResultDigest string `json:"result_digest"`
}

// LogAnalysisReceipt is compact and deliberately does not echo the report.
type LogAnalysisReceipt struct {
	AnalysisID    string                    `json:"analysis_id"`
	RequestID     string                    `json:"request_id"`
	RequestDigest string                    `json:"request_digest"`
	State         string                    `json:"state"`
	Disposition   string                    `json:"disposition"`
	Proposals     []LogAnalysisProposalLink `json:"proposals"`
}

// LogAnalysisFinalization is accepted atomically with its complete proposal batch.
type LogAnalysisFinalization struct {
	AnalysisID    string
	Generation    int64
	RequestID     string
	RequestDigest string
	Report        json.RawMessage
	State         string
	Disposition   string
	Reason        string
	Candidates    []LogAnalysisCandidate
}

func readLogAnalysis(ctx context.Context, tx *sql.Tx, id string) (LogAnalysis, error) {
	var a LogAnalysis
	var key sql.NullString
	var scope, limits, provenance, created, updated string
	err := tx.QueryRowContext(ctx, `SELECT id,start_key,request_digest,scope_json,limits_json,grant_digest,provenance_json,generation,state,disposition,calls,outbound_bytes,created_at,updated_at,reason FROM log_analyses WHERE id=?`, id).Scan(&a.ID, &key, &a.RequestDigest, &scope, &limits, &a.GrantDigest, &provenance, &a.Generation, &a.State, &a.Disposition, &a.Calls, &a.OutboundBytes, &created, &updated, &a.Reason)
	if errors.Is(err, sql.ErrNoRows) {
		return a, ErrNotFound
	}
	if err != nil {
		return a, err
	}
	a.StartKey = key.String
	a.Scope = json.RawMessage(scope)
	a.Limits = json.RawMessage(limits)
	a.Provenance = json.RawMessage(provenance)
	a.CreatedAt, err = ParseTime(created)
	if err != nil {
		return a, err
	}
	a.UpdatedAt, err = ParseTime(updated)
	return a, err
}

// CreateLogAnalysis persists before launch. A repeated start key returns the original invocation.
func (db *DB) CreateLogAnalysis(ctx context.Context, a LogAnalysis) (LogAnalysis, error) {
	if a.ID == "" || a.RequestDigest == "" || a.GrantDigest == "" || !json.Valid(a.Scope) || !json.Valid(a.Limits) {
		return a, errors.New("log analysis: invalid invocation")
	}
	if len(a.Scope) > 64<<10 || len(a.Limits) > 4096 {
		return a, errors.New("log analysis: invocation metadata too large")
	}
	if len(a.Provenance) == 0 {
		a.Provenance = json.RawMessage(`{}`)
	}
	if !json.Valid(a.Provenance) || len(a.Provenance) > 16<<10 {
		return a, errors.New("log analysis: invalid provenance")
	}
	a.Generation = 1
	a.State = "running"
	a.Disposition = "not_evaluated"
	a.Calls = 0
	a.OutboundBytes = 0
	a.CreatedAt = nowUTC()
	a.UpdatedAt = a.CreatedAt
	err := db.standardsWrite(ctx, func(tx *sql.Tx) error {
		if a.StartKey != "" {
			var id string
			e := tx.QueryRowContext(ctx, `SELECT id FROM log_analyses WHERE start_key=?`, a.StartKey).Scan(&id)
			if e == nil {
				old, e := readLogAnalysis(ctx, tx, id)
				if e != nil {
					return e
				}
				if old.RequestDigest != a.RequestDigest {
					return ErrLogAnalysisConflict
				}
				a = old
				return nil
			}
			if !errors.Is(e, sql.ErrNoRows) {
				return e
			}
		}
		var key any
		if a.StartKey != "" {
			key = a.StartKey
		}
		_, e := tx.ExecContext(ctx, `INSERT INTO log_analyses(id,start_key,request_digest,scope_json,limits_json,grant_digest,provenance_json,generation,state,disposition,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)`, a.ID, key, a.RequestDigest, string(a.Scope), string(a.Limits), a.GrantDigest, string(a.Provenance), a.Generation, a.State, a.Disposition, FormatTime(a.CreatedAt), FormatTime(a.UpdatedAt))
		return e
	})
	return a, err
}

// GetLogAnalysis reads retained state without launching or changing an invocation.
func (db *DB) GetLogAnalysis(ctx context.Context, id string) (LogAnalysis, error) {
	var a LogAnalysis
	err := db.withTx(ctx, func(tx *sql.Tx) error { var e error; a, e = readLogAnalysis(ctx, tx, id); return e })
	return a, err
}

// ListLogAnalyses pages in stable ID order; limit is capped at 100.
func (db *DB) ListLogAnalyses(ctx context.Context, after string, limit int) ([]LogAnalysis, error) {
	if limit <= 0 {
		limit = 20
	}
	if limit > 100 {
		limit = 100
	}
	out := []LogAnalysis{}
	err := db.withTx(ctx, func(tx *sql.Tx) error {
		rows, e := tx.QueryContext(ctx, `SELECT id FROM log_analyses WHERE id>? ORDER BY id LIMIT ?`, after, limit)
		if e != nil {
			return e
		}
		var ids []string
		for rows.Next() {
			var id string
			if e = rows.Scan(&id); e != nil {
				_ = rows.Close()
				return e
			}
			ids = append(ids, id)
		}
		e = rows.Err()
		_ = rows.Close()
		if e != nil {
			return e
		}
		for _, id := range ids {
			a, e := readLogAnalysis(ctx, tx, id)
			if e != nil {
				return e
			}
			out = append(out, a)
		}
		return nil
	})
	return out, err
}
func checkLogAnalysisWriter(ctx context.Context, tx *sql.Tx, id string, generation int64) (LogAnalysis, error) {
	a, e := readLogAnalysis(ctx, tx, id)
	if e != nil {
		return a, e
	}
	if a.Generation != generation || a.State != "running" {
		return a, ErrLogAnalysisConflict
	}
	return a, nil
}

// ReserveLogAnalysisBudget charges calls and encoded delivery before work; reservations are never refunded.
// The host passes its immutable limits, including any reserved communication allowance.
func (db *DB) ReserveLogAnalysisBudget(ctx context.Context, id string, generation int64, calls, bytes, maxCalls, maxBytes int) error {
	if calls < 0 || bytes < 0 || maxCalls < 0 || maxCalls > 40 || maxBytes < 0 || maxBytes > 256<<10 {
		return ErrLogAnalysisBudget
	}
	return db.standardsWrite(ctx, func(tx *sql.Tx) error {
		a, e := checkLogAnalysisWriter(ctx, tx, id, generation)
		if e != nil {
			return e
		}
		var limits struct {
			Calls int `json:"calls"`
			Bytes int `json:"bytes"`
		}
		if e = json.Unmarshal(a.Limits, &limits); e != nil {
			return e
		}
		// Callers may narrow further for diagnostic reserves, never expand the saved ceiling.
		if limits.Calls > 0 && maxCalls > limits.Calls {
			maxCalls = limits.Calls
		}
		if limits.Bytes > 0 && maxBytes > limits.Bytes {
			maxBytes = limits.Bytes
		}
		if calls > maxCalls-a.Calls || bytes > maxBytes-a.OutboundBytes {
			return ErrLogAnalysisBudget
		}
		_, e = tx.ExecContext(ctx, `UPDATE log_analyses SET calls=calls+?,outbound_bytes=outbound_bytes+?,updated_at=? WHERE id=? AND generation=? AND state='running'`, calls, bytes, FormatTime(nowUTC()), id, generation)
		return e
	})
}

// SetLogAnalysisProvenance records bounded provider profile evidence without altering scope.
func (db *DB) SetLogAnalysisProvenance(ctx context.Context, id string, generation int64, raw json.RawMessage) error {
	if !json.Valid(raw) || len(raw) > 16<<10 {
		return errors.New("log analysis: invalid provenance")
	}
	return db.standardsWrite(ctx, func(tx *sql.Tx) error {
		if _, e := checkLogAnalysisWriter(ctx, tx, id, generation); e != nil {
			return e
		}
		_, e := tx.ExecContext(ctx, `UPDATE log_analyses SET provenance_json=?,updated_at=? WHERE id=?`, string(raw), FormatTime(nowUTC()), id)
		return e
	})
}

// RecordLogAnalysisEvidence commits offered metadata before the adapter releases evidence.
func (db *DB) RecordLogAnalysisEvidence(ctx context.Context, e LogAnalysisEvidence) (LogAnalysisEvidence, error) {
	if e.CallKey == "" || !json.Valid(e.Metadata) || len(e.Metadata) > 32<<10 {
		return e, errors.New("log analysis: invalid evidence metadata")
	}
	e.CreatedAt = nowUTC()
	err := db.standardsWrite(ctx, func(tx *sql.Tx) error {
		if _, err := checkLogAnalysisWriter(ctx, tx, e.AnalysisID, e.Generation); err != nil {
			return err
		}
		var count int
		if err := tx.QueryRowContext(ctx, `SELECT COUNT(*) FROM log_analysis_evidence WHERE analysis_id=?`, e.AnalysisID).Scan(&count); err != nil {
			return err
		}
		if count >= 40 {
			return ErrLogAnalysisBudget
		}
		res, err := tx.ExecContext(ctx, `INSERT INTO log_analysis_evidence(analysis_id,generation,call_key,metadata_json,created_at) VALUES(?,?,?,?,?)`, e.AnalysisID, e.Generation, e.CallKey, string(e.Metadata), FormatTime(e.CreatedAt))
		if err != nil {
			return err
		}
		e.ID, err = res.LastInsertId()
		return err
	})
	return e, err
}

// ListLogAnalysisEvidence pages only metadata, never source bodies.
func (db *DB) ListLogAnalysisEvidence(ctx context.Context, id string, after int64, limit int) ([]LogAnalysisEvidence, error) {
	if limit <= 0 {
		limit = 20
	}
	if limit > 100 {
		limit = 100
	}
	out := []LogAnalysisEvidence{}
	rows, err := db.sql.QueryContext(ctx, `SELECT id,generation,call_key,metadata_json,created_at FROM log_analysis_evidence WHERE analysis_id=? AND id>? ORDER BY id LIMIT ?`, id, after, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		e := LogAnalysisEvidence{AnalysisID: id}
		var raw, created string
		if err = rows.Scan(&e.ID, &e.Generation, &e.CallKey, &raw, &created); err != nil {
			return nil, err
		}
		e.Metadata = json.RawMessage(raw)
		e.CreatedAt, err = ParseTime(created)
		if err != nil {
			return nil, err
		}
		out = append(out, e)
	}
	return out, rows.Err()
}
func readLogAnalysisReceipt(ctx context.Context, tx *sql.Tx, id, request string) (LogAnalysisReceipt, error) {
	var r LogAnalysisReceipt
	var raw string
	err := tx.QueryRowContext(ctx, `SELECT receipt_json FROM log_analysis_reports WHERE analysis_id=? AND request_id=?`, id, request).Scan(&raw)
	if errors.Is(err, sql.ErrNoRows) {
		return r, ErrNotFound
	}
	if err != nil {
		return r, err
	}
	err = json.Unmarshal([]byte(raw), &r)
	return r, err
}

// GetLogAnalysisReceipt recovers the exact accepted request even after its writer was fenced.
func (db *DB) GetLogAnalysisReceipt(ctx context.Context, id, request string) (LogAnalysisReceipt, error) {
	var r LogAnalysisReceipt
	err := db.withTx(ctx, func(tx *sql.Tx) error { var e error; r, e = readLogAnalysisReceipt(ctx, tx, id, request); return e })
	return r, err
}

// GetLogAnalysisReport returns the single immutable sanitized report.
func (db *DB) GetLogAnalysisReport(ctx context.Context, id string) (json.RawMessage, error) {
	var raw string
	err := db.sql.QueryRowContext(ctx, `SELECT report_json FROM log_analysis_reports WHERE analysis_id=?`, id).Scan(&raw)
	if errors.Is(err, sql.ErrNoRows) {
		err = ErrNotFound
	}
	return json.RawMessage(raw), err
}

// FinalizeLogAnalysis stores the report and creates the exact unapproved batch in one transaction.
// Candidate contents and digests must already have passed the upstream standards validator.
func (db *DB) FinalizeLogAnalysis(ctx context.Context, f LogAnalysisFinalization) (LogAnalysisReceipt, error) {
	r := LogAnalysisReceipt{AnalysisID: f.AnalysisID, RequestID: f.RequestID, RequestDigest: f.RequestDigest, State: f.State, Disposition: f.Disposition, Proposals: []LogAnalysisProposalLink{}}
	if f.RequestID == "" || f.RequestDigest == "" || !json.Valid(f.Report) || len(f.Report) > 128<<10 || len(f.Candidates) > 10 {
		return r, errors.New("log analysis: invalid final report")
	}
	if f.State != "completed" && f.State != "incomplete" && f.State != "failed" {
		return r, errors.New("log analysis: invalid final state")
	}
	if f.Disposition != "proposals" && f.Disposition != "no_warranted_change" && f.Disposition != "insufficient_evidence" && f.Disposition != "not_evaluated" {
		return r, errors.New("log analysis: invalid disposition")
	}
	if (len(f.Candidates) > 0) != (f.Disposition == "proposals") || f.State == "failed" && f.Disposition != "not_evaluated" {
		return r, errors.New("log analysis: proposal disposition mismatch")
	}
	err := db.standardsWrite(ctx, func(tx *sql.Tx) error {
		old, e := readLogAnalysisReceipt(ctx, tx, f.AnalysisID, f.RequestID)
		if e == nil {
			if old.RequestDigest != f.RequestDigest {
				return ErrLogAnalysisConflict
			}
			r = old
			return nil
		}
		if !errors.Is(e, ErrNotFound) {
			return e
		}
		if _, e = checkLogAnalysisWriter(ctx, tx, f.AnalysisID, f.Generation); e != nil {
			return e
		}
		stamp := FormatTime(nowUTC())
		seen := map[string]bool{}
		for _, c := range f.Candidates {
			p := c.Proposal
			if c.Key == "" || seen[c.Key] || p.ProposalID == "" || p.SchemaVersion != 1 || p.ChangeDigest == "" || p.ResultDigest == "" || p.Version < 0 || p.Version > 1 || len(p.Operations) == 0 {
				return errors.New("log analysis: invalid prepared proposal")
			}
			seen[c.Key] = true
			ops, e := json.Marshal(p.Operations)
			if e != nil {
				return e
			}
			p.Version = 1
			p.CreatedAt, e = ParseTime(stamp)
			if e != nil {
				return e
			}
			if e = saveStandardsProposalTx(ctx, tx, p, 0, ops); e != nil {
				return e
			}
			r.Proposals = append(r.Proposals, LogAnalysisProposalLink{CandidateKey: c.Key, ProposalID: p.ProposalID, Version: 1, BaseRevision: p.BaseRevision, ChangeDigest: p.ChangeDigest, ResultDigest: p.ResultDigest})
		}
		raw, e := json.Marshal(r)
		if e != nil {
			return e
		}
		if _, e = tx.ExecContext(ctx, `INSERT INTO log_analysis_reports(analysis_id,request_id,request_digest,report_json,receipt_json,created_at) VALUES(?,?,?,?,?,?)`, f.AnalysisID, f.RequestID, f.RequestDigest, string(f.Report), string(raw), stamp); e != nil {
			return e
		}
		for _, link := range r.Proposals {
			if _, e = tx.ExecContext(ctx, `INSERT INTO log_analysis_proposals(analysis_id,candidate_key,proposal_id,version) VALUES(?,?,?,?)`, f.AnalysisID, link.CandidateKey, link.ProposalID, link.Version); e != nil {
				return e
			}
		}
		res, e := tx.ExecContext(ctx, `UPDATE log_analyses SET state=?,disposition=?,reason=?,updated_at=?,generation=generation+1 WHERE id=? AND generation=? AND state='running'`, f.State, f.Disposition, f.Reason, stamp, f.AnalysisID, f.Generation)
		return checkLogAnalysisTransition(res, e)
	})
	if err != nil {
		return LogAnalysisReceipt{}, err
	}
	return r, nil
}

// InterruptLogAnalysis fences an orphan without resetting budgets or creating model proposals.
func (db *DB) InterruptLogAnalysis(ctx context.Context, id string, generation int64, state, reason string) error {
	if state != "incomplete" && state != "failed" {
		return errors.New("log analysis: invalid interruption state")
	}
	return db.standardsWrite(ctx, func(tx *sql.Tx) error {
		a, e := readLogAnalysis(ctx, tx, id)
		if e != nil {
			return e
		}
		if a.State != "running" {
			return nil
		}
		if a.Generation != generation {
			return ErrLogAnalysisConflict
		}
		report, e := json.Marshal(struct {
			Disposition string            `json:"disposition"`
			Reason      string            `json:"reason"`
			Findings    []json.RawMessage `json:"findings"`
		}{Disposition: "not_evaluated", Reason: reason, Findings: []json.RawMessage{}})
		if e != nil {
			return e
		}
		digest := sha256.Sum256(report)
		requestID := "host-interrupted"
		receipt := LogAnalysisReceipt{AnalysisID: id, RequestID: requestID, RequestDigest: hex.EncodeToString(digest[:]), State: state, Disposition: "not_evaluated", Proposals: []LogAnalysisProposalLink{}}
		raw, e := json.Marshal(receipt)
		if e != nil {
			return e
		}
		stamp := FormatTime(nowUTC())
		if _, e = tx.ExecContext(ctx, `INSERT INTO log_analysis_reports(analysis_id,request_id,request_digest,report_json,receipt_json,created_at) VALUES(?,?,?,?,?,?)`, id, requestID, receipt.RequestDigest, string(report), string(raw), stamp); e != nil {
			return e
		}
		res, e := tx.ExecContext(ctx, `UPDATE log_analyses SET generation=generation+1,state=?,disposition='not_evaluated',reason=?,updated_at=? WHERE id=? AND generation=? AND state='running'`, state, reason, stamp, id, generation)
		return checkLogAnalysisTransition(res, e)
	})
}

// GetAnalystStandardsBinding uses a namespace distinct from workflow root run IDs.
func (db *DB) GetAnalystStandardsBinding(ctx context.Context, id string) (StandardsRunBinding, error) {
	var b StandardsRunBinding
	err := db.withTx(ctx, func(tx *sql.Tx) error {
		var root string
		e := tx.QueryRowContext(ctx, `SELECT root_key FROM log_analysis_books WHERE analysis_id=?`, id).Scan(&root)
		if errors.Is(e, sql.ErrNoRows) {
			return ErrNotFound
		}
		if e != nil {
			return e
		}
		b, e = readRunBinding(ctx, tx, root)
		return e
	})
	return b, err
}

// SaveAnalystStandardsBinding retains a book against a real standalone invocation row.
func (db *DB) SaveAnalystStandardsBinding(ctx context.Context, id string, b StandardsRunBinding) (StandardsRunBinding, error) {
	b.RootRunID = "analysis:" + id
	b.Canonical = string(b.SnapshotBytes)
	b.CapturedAt = nowUTC()
	if len(b.SnapshotBytes) > 16<<20 {
		return b, errors.New("log analysis: retained standards capture exceeds 16 MiB")
	}
	raw, err := json.Marshal(b)
	if err != nil {
		return b, err
	}
	err = db.standardsWrite(ctx, func(tx *sql.Tx) error {
		a, e := readLogAnalysis(ctx, tx, id)
		if e != nil {
			return e
		}
		if a.State != "running" {
			return ErrLogAnalysisConflict
		}
		if _, e = tx.ExecContext(ctx, `INSERT INTO standards_run_bindings(root_run_id,binding_json) VALUES(?,?) ON CONFLICT(root_run_id) DO NOTHING`, b.RootRunID, string(raw)); e != nil {
			return e
		}
		if _, e = tx.ExecContext(ctx, `INSERT INTO log_analysis_books(analysis_id,root_key) VALUES(?,?) ON CONFLICT(analysis_id) DO NOTHING`, id, b.RootRunID); e != nil {
			return e
		}
		b, e = readRunBinding(ctx, tx, b.RootRunID)
		return e
	})
	return b, err
}

// LogAnalysisRunHighWater freezes the largest allocated workflow run before launch.
func (db *DB) LogAnalysisRunHighWater(ctx context.Context) (int64, error) {
	var id int64
	err := db.sql.QueryRowContext(ctx, `SELECT COALESCE(MAX(id),0) FROM runs`).Scan(&id)
	return id, err
}

// ListLogAnalysisProposalLinks reads immutable exact versions, independent of later edits.
func (db *DB) ListLogAnalysisProposalLinks(ctx context.Context, id string) ([]LogAnalysisProposalLink, error) {
	out := []LogAnalysisProposalLink{}
	rows, err := db.sql.QueryContext(ctx, `SELECT l.candidate_key,p.proposal_id,p.version,p.base_revision,p.change_digest,p.result_digest FROM log_analysis_proposals l JOIN standards_proposal_versions p ON p.proposal_id=l.proposal_id AND p.version=l.version WHERE l.analysis_id=? ORDER BY l.candidate_key`, id)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		var l LogAnalysisProposalLink
		var base sql.NullInt64
		if err = rows.Scan(&l.CandidateKey, &l.ProposalID, &l.Version, &base, &l.ChangeDigest, &l.ResultDigest); err != nil {
			return nil, err
		}
		l.BaseRevision = base.Int64
		out = append(out, l)
	}
	return out, rows.Err()
}

// CheckLogAnalysisWriter authorizes each live operation against the durable generation.
func (db *DB) CheckLogAnalysisWriter(ctx context.Context, id string, generation int64) error {
	return db.withTx(ctx, func(tx *sql.Tx) error { _, e := checkLogAnalysisWriter(ctx, tx, id, generation); return e })
}

// RecordLogAnalysisProviderResult retains host-observed completion after submission
// has fenced the writer. It cannot alter the accepted report or grant another launch.
func (db *DB) RecordLogAnalysisProviderResult(ctx context.Context, id string, originalGeneration int64, raw json.RawMessage) error {
	if !json.Valid(raw) || len(raw) > 16<<10 {
		return errors.New("log analysis: invalid provider result")
	}
	return db.standardsWrite(ctx, func(tx *sql.Tx) error {
		a, e := readLogAnalysis(ctx, tx, id)
		if e != nil {
			return e
		}
		if !logAnalysisRecoveryGeneration(a, originalGeneration) {
			return ErrLogAnalysisConflict
		}
		_, e = tx.ExecContext(ctx, `UPDATE log_analyses SET provenance_json=?,updated_at=? WHERE id=?`, string(raw), FormatTime(nowUTC()), id)
		return e
	})
}

func logAnalysisRecoveryGeneration(a LogAnalysis, original int64) bool {
	return original > 0 && (a.Generation == original && a.State == "running" || a.Generation == original+1 && a.State != "running")
}

// ReserveLogAnalysisRecoveryBudget charges only the host's receipt/replay delivery
// after finalization, using the same permanently consumed invocation allowance.
func (db *DB) ReserveLogAnalysisRecoveryBudget(ctx context.Context, id string, originalGeneration int64, calls, bytes int) error {
	if calls < 0 || bytes < 0 {
		return ErrLogAnalysisBudget
	}
	return db.standardsWrite(ctx, func(tx *sql.Tx) error {
		a, e := readLogAnalysis(ctx, tx, id)
		if e != nil {
			return e
		}
		if !logAnalysisRecoveryGeneration(a, originalGeneration) {
			return ErrLogAnalysisConflict
		}
		var limits struct {
			Calls int `json:"calls"`
			Bytes int `json:"bytes"`
		}
		if e = json.Unmarshal(a.Limits, &limits); e != nil {
			return e
		}
		maxCalls, maxBytes := 40, 256<<10
		if limits.Calls > 0 && limits.Calls < maxCalls {
			maxCalls = limits.Calls
		}
		if limits.Bytes > 0 && limits.Bytes < maxBytes {
			maxBytes = limits.Bytes
		}
		if calls > maxCalls-a.Calls || bytes > maxBytes-a.OutboundBytes {
			return ErrLogAnalysisBudget
		}
		_, e = tx.ExecContext(ctx, `UPDATE log_analyses SET calls=calls+?,outbound_bytes=outbound_bytes+?,updated_at=? WHERE id=?`, calls, bytes, FormatTime(nowUTC()), id)
		return e
	})
}

func checkLogAnalysisTransition(result sql.Result, err error) error {
	if err != nil {
		return err
	}
	n, err := result.RowsAffected()
	if err != nil {
		return err
	}
	if n != 1 {
		return ErrLogAnalysisConflict
	}
	return nil
}
