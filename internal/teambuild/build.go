// Package teambuild turns one team folder under teams/source into the exact
// files an installation holds. It copies the source as it is, fills the
// {{var}} placeholders that inherit.json names, adds the generated team.config
// and checks the result against the factory workflows. It never writes files.
package teambuild

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/cloudvane/litefactory/internal/agent"
	"github.com/cloudvane/litefactory/internal/config"
	"github.com/cloudvane/litefactory/internal/graphexec"
	"github.com/cloudvane/litefactory/internal/skillclosure"
	"github.com/cloudvane/litefactory/internal/teampackage"
	"github.com/cloudvane/litefactory/internal/teamsource"
	"github.com/cloudvane/litefactory/internal/turn"
)

// Workflows are the workflow folders every team carries. The Doctor is not
// one of them: it is a factory library workflow (teams/source/factory/doctor).
var Workflows = []string{"bug", "implement", "plan", "research", "spike", "validate"}

// outOfGraphSkills lists, per workflow, the skills an installation carries
// although no graph node binds them. Their full skill closure is installed; any
// other file outside the captured role closure is refused.
var outOfGraphSkills = map[string][]string{"research": {"brainstorm", "brainstorm-drafts"}}

// Build resolves teams/source/<slug> under sourceRoot, the absolute path of a
// teams/source folder, and returns the installable files with their release
// inventory, per-file hashes and checksum.
func Build(ctx context.Context, sourceRoot, slug string) (map[string][]byte, teampackage.Release, error) {
	var release teampackage.Release
	if !filepath.IsAbs(sourceRoot) {
		return nil, release, errors.New("team source: an absolute teams/source folder is required")
	}
	if !teamsource.SafePath(slug) || strings.Contains(slug, "/") {
		return nil, release, fmt.Errorf("team %q: not a team folder name", slug)
	}
	sourceRoot = filepath.Clean(sourceRoot)
	// The root is the folder above teams/source so a team's inherit.json can
	// name its base as a sibling folder.
	root, err := os.OpenRoot(filepath.Dir(sourceRoot))
	if err != nil {
		return nil, release, err
	}
	defer root.Close()
	return build(ctx, root, filepath.Base(sourceRoot)+"/"+slug, slug)
}

func build(ctx context.Context, root *os.Root, dir, slug string) (map[string][]byte, teampackage.Release, error) {
	var release teampackage.Release
	if info, err := root.Lstat(dir); err != nil || !info.IsDir() {
		return nil, release, fmt.Errorf("%s: no team folder named %s", dir, slug)
	}
	if err := teamsource.RefuseBase(root, dir); err != nil {
		return nil, release, err
	}
	raw, err := teamsource.ReadSourceFile(root, dir+"/release.json")
	if err != nil {
		return nil, release, err
	}
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	if err := d.Decode(&release); err != nil {
		return nil, release, fmt.Errorf("%s/release.json: %w", dir, err)
	}
	if err := d.Decode(new(any)); !errors.Is(err, io.EOF) {
		return nil, release, fmt.Errorf("%s/release.json: trailing JSON", dir)
	}
	if release.Slug != slug || !teamsource.SafePath(release.Download) || !strings.HasPrefix(release.Download, release.Slug+"/") || len(release.Files) != 0 || release.Checksum != "" {
		return nil, release, fmt.Errorf("%s/release.json: slug must be %q, download a path under it, and no authored hashes", dir, slug)
	}
	files, err := teamsource.ResolveSource(ctx, root, dir, release.Slug)
	if err != nil {
		return nil, release, err
	}
	profile, ok := files["stack-profile.json"]
	if !ok {
		return nil, release, errors.New("stack-profile.json: missing from the resolved source")
	}
	decoded, err := config.DecodeStackProfile(profile)
	if err != nil {
		return nil, release, err
	}
	for _, w := range Workflows {
		graph, ok := files[w+"/"+w+".dot"]
		if !ok || !bytes.Contains(graph, []byte(`team="`+release.Slug+`"`)) {
			return nil, release, fmt.Errorf("%s/%s.dot: missing selected team graph identity", w, w)
		}
	}
	// The mode classifier is a team role outside every workflow folder.
	if role, ok := files[teamsource.ModeClassifierPath]; !ok || len(bytes.TrimSpace(role)) == 0 {
		return nil, release, fmt.Errorf("%s: missing or blank in the resolved source", teamsource.ModeClassifierPath)
	}
	mapping := map[string]string{}
	teamConfig := []byte("# Generated by litefactory team install from teams/source. Edit the source only.\n")
	for _, w := range Workflows {
		mapping[w] = w + "/" + w + ".dot"
		teamConfig = append(teamConfig, []byte("  "+w+": "+mapping[w]+"\n")...)
	}
	files["team.config"] = teamConfig
	guidanceFiles, err := teamsource.CaptureStackGuidance(ctx, teamsource.RetainedFiles(files), decoded)
	if err != nil {
		return nil, release, err
	}
	if err := turn.ValidateTeamWorkflows(ctx, teamsource.RetainedFiles(files), mapping); err != nil {
		return nil, release, fmt.Errorf("team workflows: %w", err)
	}
	builders := map[string]func() (graphexec.Registry, error){"research": turn.ResearchSpecs, "plan": turn.PlanSpecs, "implement": turn.ImplementSpecs, "validate": turn.ValidateFlowSpecs, "spike": turn.SpikeSpecs, "bug": turn.BugSpecs}
	for _, w := range Workflows {
		registry, err := builders[w]()
		if err != nil {
			return nil, release, err
		}
		source, err := fs.Sub(teamsource.RetainedFiles(files), w)
		if err != nil {
			return nil, release, err
		}
		definition, err := teamsource.CaptureWorkflowIdentity(ctx, source, w+".dot", release.Slug, agent.Workflow(w), registry)
		if err != nil {
			return nil, release, err
		}
		extra, err := outOfGraphClosure(files, w)
		if err != nil {
			return nil, release, err
		}
		for name := range files {
			rest, ok := strings.CutPrefix(name, w+"/")
			if !ok {
				continue
			}
			if _, ok := definition.Files[rest]; ok {
				continue
			}
			if _, selected := guidanceFiles[name]; selected {
				continue
			}
			if _, listed := extra[rest]; listed {
				continue
			}
			return nil, release, fmt.Errorf("%s: resource is outside the captured role closure", name)
		}
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	slices.Sort(names)
	h := sha256.New()
	for _, name := range names {
		sum := sha256.Sum256(files[name])
		hash := hex.EncodeToString(sum[:])
		release.Files = append(release.Files, teampackage.File{Path: name, SHA256: hash})
		_, _ = io.WriteString(h, name+"\x00"+hash+"\n")
	}
	release.Checksum = hex.EncodeToString(h.Sum(nil))
	return files, release, nil
}

// outOfGraphClosure loads the skill closure of the listed out-of-graph skills
// present in workflow w, keyed by workflow-relative path.
func outOfGraphClosure(files map[string][]byte, w string) (map[string][]byte, error) {
	var selected []string
	for _, skill := range outOfGraphSkills[w] {
		if _, ok := files[w+"/skills/"+skill+"/SKILL.md"]; ok {
			selected = append(selected, skill)
		}
	}
	if len(selected) == 0 {
		return nil, nil
	}
	_, closure, err := skillclosure.Load(selected, func(name string) ([]byte, error) {
		raw, ok := files[w+"/"+name]
		if !ok {
			return nil, fmt.Errorf("%s/%s: %w", w, name, fs.ErrNotExist)
		}
		return raw, nil
	})
	if err != nil {
		return nil, fmt.Errorf("%s out-of-graph skills: %w", w, err)
	}
	return closure, nil
}
